/**
 * ISO 3166-1 alpha-2 → numeric (the COUNTRIES_MAP region id), the Natural Earth name the map
 * uses for it, and the hint group said after a first miss. Covers every country a landmark (or a
 * flag in src/apps/flags) points at; a unit test checks each numeric against the generated map.
 */

export type HintGroup = 'Europe' | 'Asia' | 'Africa' | 'North America' | 'South America' | 'Oceania' | 'Europe and Asia';

