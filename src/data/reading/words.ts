/**
 * Read Words — curated levels from pre-K CVC words to the end of 2nd grade.
 *
 * Order follows a typical phonics scope & sequence (short vowels → digraphs → blends →
 * magic e → vowel teams → r-controlled → diphthongs → endings → two syllables), with Dolch /
 * Fry sight-word levels mixed in between. Every word has a short kid-friendly sentence that
 * is shown (and can be heard) after he reads the word.
 *
 * Entry: [word, sentence] or [word, sentence, alternates] — alternates are other spellings the
 * recognizer may produce for the same spoken word (homophones are handled by the matcher).
 */

export type WordEntry = [word: string, sentence: string, alternates?: string[]];

