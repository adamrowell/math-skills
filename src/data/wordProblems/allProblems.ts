export const allWordProblems: WordProblem[] = [
  ...letterPatternProblems,
  ...rhymingProblems,
  ...synonymAntonymProblems,
  ...wordMathProblems,
  ...sequenceProblems,
  ...comprehensionProblems,
];

// Get problems by category
export function getProblemsByCategory(category: ProblemCategory): WordProblem[] {
  return allWordProblems.filter(p => p.category === category);
}

// Get problems by difficulty
export function getProblemsByDifficulty(difficulty: number): WordProblem[] {
  return allWordProblems.filter(p => p.difficulty <= difficulty);
}

// Get random problem
export function getRandomProblem(
  categories?: ProblemCategory[],
  maxDifficulty?: number,
  excludeIds?: string[]
): WordProblem | null {
  let filtered = allWordProblems;

  if (categories && categories.length > 0) {
    filtered = filtered.filter(p => categories.includes(p.category));
  }

  if (maxDifficulty) {
    filtered = filtered.filter(p => p.difficulty <= maxDifficulty);
  }

  if (excludeIds && excludeIds.length > 0) {
    filtered = filtered.filter(p => !excludeIds.includes(p.id));
  }

  if (filtered.length === 0) return null;

  return filtered[Math.floor(Math.random() * filtered.length)];
}

