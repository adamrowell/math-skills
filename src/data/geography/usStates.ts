// Get states by region
export function getStatesByRegion(region: 'west' | 'midwest' | 'south' | 'northeast'): USStateData[] {
  return usStates.filter(state => state.region === region);
}

// Get state by abbreviation
export function getStateByAbbreviation(abbr: string): USStateData | undefined {
  return usStates.find(state => state.abbreviation === abbr.toUpperCase());
}

// Get state by name
export function getStateByName(name: string): USStateData | undefined {
  return usStates.find(state => state.name.toLowerCase() === name.toLowerCase());
}

// Get random state
export function getRandomState(exclude?: string[]): USStateData {
  const available = exclude
    ? usStates.filter(s => !exclude.includes(s.id))
    : usStates;
  return available[Math.floor(Math.random() * available.length)];
}

export default usStates;
