// Get landmarks by category
export function getLandmarksByCategory(category: LandmarkData['category']): LandmarkData[] {
  return landmarks.filter(landmark => landmark.category === category);
}

// Get landmarks by country
export function getLandmarksByCountry(countryCode: string): LandmarkData[] {
  return landmarks.filter(landmark => landmark.countryCode === countryCode.toUpperCase());
}

// Get landmark by ID
export function getLandmarkById(id: string): LandmarkData | undefined {
  return landmarks.find(landmark => landmark.id === id);
}

// Get random landmark
export function getRandomLandmark(category?: LandmarkData['category'], exclude?: string[]): LandmarkData {
  let available = category
    ? landmarks.filter(l => l.category === category)
    : landmarks;

  if (exclude) {
    available = available.filter(l => !exclude.includes(l.id));
  }

  return available[Math.floor(Math.random() * available.length)];
}

export default landmarks;
