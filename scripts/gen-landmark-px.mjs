#!/usr/bin/env node
/**
 * Pre-projects every landmark to map pixels (the maps have no runtime projection):
 *   world: geoNaturalEarth1().fitWidth(1000, Sphere) — identical to src/apps/maps/tools/gen-geo.mjs
 *   US:    geoAlbersUsa().scale(1300).translate([487.5, 305]) — us-atlas' states-albers-10m projection
 *
 *   node scripts/gen-landmark-px.mjs
 *
 * Output: src/apps/landmarks/data/landmarks.gen.ts (committed).
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadLandmarks, repoRoot } from './lib/load-landmarks.mjs';

const require = createRequire(import.meta.url);
const d3 = require('d3-geo');

const world = d3.geoNaturalEarth1();
world.fitWidth(1000, { type: 'Sphere' });
const us = d3.geoAlbersUsa().scale(1300).translate([487.5, 305]);

const r1 = (n) => Math.round(n * 10) / 10;
const LANDMARKS = await loadLandmarks();
const rows = LANDMARKS.map((l) => {
  const [wx, wy] = world([l.lon, l.lat]);
  const row = { id: l.id, wx: r1(wx), wy: r1(wy) };
  if (l.state) {
    const p = us([l.lon, l.lat]);
    if (!p) throw new Error(`${l.id}: outside the US projection`);
    row.ux = r1(p[0]);
    row.uy = r1(p[1]);
  }
  return row;
});

const body =
  '// GENERATED by scripts/gen-landmark-px.mjs — do not edit by hand.\n' +
  "export interface LandmarkPx {\n  id: string;\n  wx: number;\n  wy: number;\n  ux?: number;\n  uy?: number;\n}\n\n" +
  `export const LANDMARK_PX: LandmarkPx[] = [\n${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}\n];\n`;
writeFileSync(join(repoRoot, 'src/apps/landmarks/data/landmarks.gen.ts'), body);
console.log('landmarks.gen.ts', rows.length, 'pins');
